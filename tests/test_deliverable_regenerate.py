"""WF-07 / B-02: the row that says "regenerate before sending" can regenerate.

The affordance invariant's own first founding instance, quoted verbatim in
`.claude/agents/auditor.md` - *"the Deliverables table says 'regenerate before
sending' with no regenerate control"*. It stood as an open High for the whole
life of the register that names it, and on 21 August 2026 nine client-facing
comparison documents for a live client walked into it: the WF-75 adopt pass
(`08f663d`) gave every orphan on disk a row, and the nine recovered
`www-acme-com-au-comparison-client-2026-08-17-*` documents carry
`renderer_version` NULL, which `client_reports()` renders as `unknown` and this
screen renders as an instruction the table has no verb for.

**Why the branch had to be painted before it could be guarded.** The rendered
sweep reaches `#/sites/{site}/reports`, so the table is covered - but the
fixture's only deliverable is generated by `POST /api/reports` at the current
`RENDERER_VERSION`, so `renderer` is `current` and neither the `superseded` nor
the `unknown` branch has ever been drawn in this suite's life. Listed is not
painted; DISCIPLINE rule 4. Each live clause below amends the *stored*
`renderer_version` rather than arranging a screen state, for the same reason
`test_heading_fault.py` un-places a stored finding: the case rendered is then a
real row the server built, not one this file invented.

**Regenerating spends nothing**, which is why the control carries no
`SpendMark` and needs no confirmation - `clauditseo/reporting/generate.py`
reaches no provider (`providers_failing` and `providers_answering` are read out
of stored evidence), and `test_a11y_rendered.py`'s own fixture says it outright:
"A deliverable needs no model". Marking a control that does not spend is what
`e979b1c` reverted `711557e` for.

**The `file missing` branch is deliberately out of scope here.** A row whose
file has been moved also states something the operator cannot act on, but a
regeneration produces a *new* document with a new id and leaves that row as
broken as it was - a different remedy, and one worth deciding on its own rather
than absorbing into this one.
"""

